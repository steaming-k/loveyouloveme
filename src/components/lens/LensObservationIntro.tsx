import { LovyMessage } from '@/components/lovy/LovyMessage';

/**
 * 단독 Lens 화면(`/lens/saju` · `/lens/astrology`)의 **연속성 메모** (Concept Continuity 260915)
 *
 * ══ 왜 필요했나 ═══════════════════════════════════════════════════════════
 *
 * Premium 리포트 안의 렌즈 섹션에는 이미 이 문장이 있다(`LENS_SECTION_COPY.intro`):
 *
 * > 여기부터는 같은 관계를 다른 프레임으로 다시 본 거야.
 *
 * 그런데 **단독 렌즈 화면에는 그 말이 없었다.** 화면은 이렇게 시작한다:
 *
 * ```
 * ENTERTAINMENT
 * 사주 렌즈
 * 나의 일주 · 경자(庚子)일 …
 * ```
 *
 * 앞 화면까지 러비가 관찰하고 이어보던 흐름이 여기서 끊기고, 일반 사주/별자리 앱의
 * 결과 페이지처럼 읽힌다. MBTI 렌즈는 이미 `러비 관찰 기록 · 렌즈` 헤더와
 * `그런데 실제 관계에서는?` 블록으로 관계로 되돌아오는데, 나머지 둘만 그게 없었다 —
 * 세 렌즈가 서로 다른 문법을 쓰고 있었던 셈이다.
 *
 * ══ 이 컴포넌트가 하는 일과 하지 않는 일 ══════════════════════════════════
 *
 * 하는 일: **직전까지 본 것과 지금 보는 것을 한 문장으로 잇는다.** 그것뿐이다.
 *
 * ⚠️ **해석을 만들지 않는다.** 렌즈 결과·판정·근거에 접근하지 않고 렌즈 이름만 받는다.
 *    여기서 관계에 대한 문장을 만들면 그건 계산을 거치지 않은 해석이 된다.
 * ⚠️ **면책 문구를 반복하지 않는다.** '동기화율에 반영하지 않는다'는 각 화면 하단의
 *    `EntertainmentNotice`가 이미 말한다 — 위아래에서 같은 말을 두 번 하면 그건
 *    강조가 아니라 Value Density 손해다.
 * ⚠️ **큰 카드를 만들지 않는다.** 러비 44px + 한 문장이다. 렌즈 결과보다 캐릭터가
 *    커 보이면 실패다(§26과 같은 규칙).
 */
export function LensObservationIntro({ lens }: { lens: '사주' | '별자리' }) {
  return (
    <LovyMessage pose="note" size={40}>
      지금까지는 네가 답한 관계 신호를 봤어. 이번엔 같은 관계를 {lens} 렌즈로 한 번 더 볼게.
    </LovyMessage>
  );
}
