/**
 * **두 사람의 조합에서 눈여겨볼 성향 패턴.**
 *
 * ⚠️ 이것은 **궁합표가 아니다.** 16 × 16 = 256개 유형쌍마다 문장을 쓰면 그 순간
 * 'INFP × ESTJ는 이렇다'는 궁합 사전이 된다. 그래서 유형쌍이 아니라 **네 축이
 * 같음/다름으로 만드는 구조**만 읽는다 — 버킷은 아래 5개뿐이고 256개 조합 전부가
 * 이 중 하나에 정확히 들어간다.
 *
 * 축을 두 묶음으로 나누는 기준은 MBTI 자체의 표준 구분을 그대로 쓴다:
 *   INNER  정보를 받아들이고(S/N) 판단하는(T/F) 과정
 *   OUTER  에너지를 회복하고(E/I) 생활을 조직하는(J/P) 리듬
 *
 * 문체 규칙은 이 파일의 다른 문구와 같다 — '~로 이야기되기도 해' / '~일 수 있어'.
 * 좋고 나쁨·성공률·천생연분/상극·퍼센트를 만들지 않는다.
 */
export interface MbtiPatternDefinition {
  key: MbtiPatternKey;
  /** 패턴 이름 — 판정이 아니라 모양의 설명이다 */
  label: string;
  /** 2~3문장. '이 조합에서 무엇을 눈여겨볼지' */
  body: string;
  /** 한 줄 — 이 패턴에서 흔히 어긋난다고 이야기되는 지점 */
  watchFor: string;
}

