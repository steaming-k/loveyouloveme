interface MbtiAxisDefinition {
  key: MbtiAxisKey;
  /** MBTI 4글자 중 몇 번째 자리인지 */
  index: 0 | 1 | 2 | 3;
  eyebrow: string;
  label: string;
  /**
   * 축 양 끝(글자)의 짧은 이름 (v1.24 §7/§8)
   *
   * ⚠️ 새로운 주장을 만든 값이 아니다. 아래 `same`/`different` 문장에 이미 쓰여 있던
   * 표현을 그대로 짧게 줄인 것이다 — 예: `same.I`의 "혼자 있는 시간으로 에너지를
   * 회복하는" → `I: '혼자 있는 시간으로 회복'`. 데이터가 지원하지 않는 의미
   * ('내향적인 사람' 같은 유형 단정)를 새로 만들지 않는다.
   *
   * 4축 비교표에서 marker 옆 **텍스트 라벨**로 쓴다 — 위치·색만으로 구분하지 않기 위해서다.
   */
  poles: Record<string, string>;
  /** 두 사람의 글자가 같을 때 — 글자별 문장 */
  same: Record<string, string>;
  /** 두 사람의 글자가 다를 때 */
  different: string;
  /**
   * 글자가 다른 축에 대해 S25에 덧붙일 수 있는 대화 질문.
   *
   * ⚠️ **반드시 그 축과 같은 층위에 머문다** (v1.25 Audit).
   * 이 질문은 두 사람의 글자가 **다를 때만** 나온다. 그래서 질문이 특정 연애 행동을
   * 지목하면 "너희 J/P가 다르니까 데이트 계획 취향도 다를 것이다"라는 **예측**이
   * 질문의 형태로 숨어든다 — MBTI를 실제 행동과 1:1 대응시키는 것과 같다.
   *
   * 그래서 질문은 '이 축에서 너는 실제로 어느 쪽이야?'까지만 묻는다. 축 밖의 구체
   * 상황(데이트 계획 · 갈등 상황의 반응 등)으로 넘어가지 않는다.
   */
  question: string;
}

